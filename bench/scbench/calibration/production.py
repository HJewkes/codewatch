"""Which files of a project count as production code for calibration (Alves 2010: tests pull
thresholds down and generated code pushes them up).

Excluded anywhere in the path: dilution.py's tool and environment dirs, dot-dirs, test dirs, vendored
dirs and migration dirs. Excluded only at the top level (or directly under `src/`): docs, examples,
benchmarks, scripts, tools and CI dirs, which inside a package are often real code. Excluded files:
test modules, conftest.py, top-level build and task scripts, protobuf stubs, and any file whose first
2 KB carries a generated-code marker.
"""

from __future__ import annotations

import re
from pathlib import Path

ANYWHERE = {"tests", "test", "testing", "testsuite", "unittests", "vendor", "vendored", "_vendor",
            "third_party", "thirdparty", "externals", "extern", "migrations", "__pycache__", "build",
            "dist", "node_modules", "site-packages", "venv", "env", "fixtures"}
TOP_LEVEL = {"docs", "doc", "examples", "example", "samples", "sample", "demo", "demos", "benchmarks",
             "benchmark", "bench", "asv_bench", "scripts", "tools", "ci", "contrib", "devtools"}
TOP_FILES = {"setup.py", "noxfile.py", "tasks.py", "fabfile.py", "conf.py", "runtests.py", "dodo.py",
             "hatch_build.py", "conftest.py", "versioneer.py", "release.py", "bootstrap.py"}
GENERATED = re.compile(r"(?i)(generated by|auto-?generated|do not edit|code generated|autogenerated)")
GENERATED_SUFFIXES = ("_pb2.py", "_pb2_grpc.py")


def is_test_file(name: str) -> bool:
    return name.startswith("test_") or name.endswith(("_test.py", "_tests.py")) or name == "conftest.py"


def excluded_path(parts: tuple[str, ...]) -> bool:
    dirs, name = parts[:-1], parts[-1]
    if any(d.startswith(".") or d in ANYWHERE for d in dirs):
        return True
    top = dirs[1:2] if dirs[:1] == ("src",) else dirs[:1]
    if top and top[0] in TOP_LEVEL:
        return True
    if not dirs and name in TOP_FILES:
        return True
    return is_test_file(name) or name.endswith(GENERATED_SUFFIXES)


def is_generated(text: str) -> bool:
    return bool(GENERATED.search(text[:2048]))


def production_files(root: Path) -> list[tuple[str, str]]:
    """(posix relative path, text) for every production .py file under root, sorted by path."""
    out = []
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root)
        if path.is_symlink() or not path.is_file() or excluded_path(rel.parts):
            continue
        text = path.read_text(errors="replace")
        if not is_generated(text):
            out.append((rel.as_posix(), text))
    return out
