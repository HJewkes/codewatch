NESTED = textwrap.dedent('''
    class Box:
        def __init__(self, a):
            self.a = a

        @staticmethod
        def make():
            return Box(1)

        def run(self, x, y=2, *rest, **opts):
            """Not code."""
            def inner(z):
                if z and x:
                    return 1
                return 0
            if x:
                return inner(y)
            return 0
''')


def fn(src):
    return ast.parse(textwrap.dedent(src)).body[0]


def write(root, files):
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(textwrap.dedent(text))


class ProductionFiles(unittest.TestCase):
    def test_tests_and_vendored_code_are_left_out_wherever_they_sit(self):
        for parts in [("pkg", "tests", "x.py"), ("pkg", "_vendor", "six.py"), ("pkg", "test_api.py"),
                      ("pkg", "api_test.py"), ("pkg", "conftest.py"), ("pkg", "migrations", "0001.py")]:
            self.assertTrue(excluded_path(parts), parts)

    def test_docs_and_scripts_are_left_out_only_at_the_top_level(self):
        self.assertTrue(excluded_path(("docs", "conf.py")))
        self.assertTrue(excluded_path(("src", "examples", "demo.py")))
        self.assertFalse(excluded_path(("pkg", "examples", "loader.py")))
        self.assertTrue(excluded_path(("setup.py",)))
        self.assertFalse(excluded_path(("pkg", "setup.py")))

    def test_a_generated_marker_near_the_top_marks_the_file_generated(self):
        self.assertTrue(is_generated("# Generated by the protocol buffer compiler.  DO NOT EDIT!\n"))
        self.assertFalse(is_generated("def f():\n    return 1\n" + "\n" * 3000 + "# generated by hand\n"))


class UnitMeasures(unittest.TestCase):
    def test_own_body_measures_leave_nested_functions_out_and_scb_cc_keeps_them(self):
        module = measure_module("pkg/box.py", NESTED)
        run = next(u for u in module["units"] if u["key"] == "pkg/box.py:Box.run")
        self.assertEqual((run["cc"], run["cc_scb"]), (2, 4))
        self.assertEqual(run["sloc"], 4)
        self.assertEqual(run["in"], 4)

    def test_class_methods_leave_out_init_and_static_methods(self):
        module = measure_module("pkg/box.py", NESTED)
        self.assertEqual(module["classes"][0]["methods"], 1)

    def test_cognitive_charges_nesting_and_one_per_boolean_run(self):
        loop = fn("""
            def f(xs):
                for x in xs:
                    if x and x > 1 and x < 9:
                        return x
                    elif x or x is None:
                        return 0
        """)
        self.assertEqual(cognitive(loop), 1 + 2 + 1 + 1 + 1)

    def test_an_unparseable_module_is_skipped(self):
        self.assertIsNone(measure_module("bad.py", "def (:\n"))


class ProjectMeasures(unittest.TestCase):
    def test_project_counts_production_code_and_import_coupling(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            write(root, {"src/pkg/__init__.py": "from .core import run\n",
                         "src/pkg/core.py": "from pkg import util\n\ndef run(x):\n    return util.twice(x)\n",
                         "src/pkg/util.py": "def twice(x):\n    return 2 * x\n",
                         "tests/test_core.py": "def test_run():\n    assert True\n",
                         "setup.py": "import setuptools\n"})
            measured = measure_project(root)
        modules = {m["path"]: m for m in measured["modules"]}
        self.assertEqual(sorted(modules), ["src/pkg/__init__.py", "src/pkg/core.py", "src/pkg/util.py"])
        self.assertEqual((modules["src/pkg/util.py"]["fan_in"], modules["src/pkg/util.py"]["instability"]), (1, 0.0))
        self.assertEqual((modules["src/pkg/core.py"]["fan_in"], modules["src/pkg/core.py"]["fan_out"]), (1, 1))
        self.assertEqual(measured["sloc"], 6)


def system(values):
    units = [{"cc": v, "cc_scb": v, "cog": v, "in": 1, "sloc": s} for v, s in values]
    return {"units": units, "classes": [], "modules": []}


class Curves(unittest.TestCase):
    def test_quantiles_are_read_by_share_of_code_not_share_of_functions(self):
        pairs = curves.system_pairs([{"cc": 1, "sloc": 10}] * 9 + [{"cc": 20, "sloc": 90}], "cc")
        self.assertEqual(curves.weighted_quantiles(pairs), [20, 20, 20])

    def test_every_system_counts_equally_whatever_its_size(self):
        big = [{"cc": 1, "sloc": 1000}]
        small = [{"cc": 5, "sloc": 1}, {"cc": 9, "sloc": 1}]
        pairs = curves.system_pairs(big, "cc") + curves.system_pairs(small, "cc")
        self.assertEqual(curves.weighted_quantiles(pairs, (0.5, 0.7, 0.9)), [1, 5, 9])

    def test_band_shares_split_a_system_by_sloc(self):
        edges = {"p70": 5, "p80": 10, "p90": 15}
        rows = [{"cc": 1, "sloc": 50}, {"cc": 7, "sloc": 25}, {"cc": 30, "sloc": 25}]
        self.assertEqual(curves.band_shares(rows, "cc", edges),
                         {"low": 0.5, "moderate": 0.25, "high": 0.0, "very_high": 0.25})

    def test_derived_curves_mark_the_cognitive_port_provisional(self):
        derived = curves.derive([system([(1, 10), (3, 10)])])
        self.assertTrue(derived["complexity"]["cog"]["provisional"])
        self.assertNotIn("provisional", derived["complexity"]["cc"])


def stats(**overrides):
    base = dict(fork=False, archived=False, python_share=0.9, commits=500, authors=20, days_since_commit=30,
                sloc=10_000)
    return corpus.Stats(**{**base, **overrides})


class Selection(unittest.TestCase):
    def test_a_maintained_python_project_passes(self):
        self.assertIsNone(corpus.rejection(stats()))

    def test_each_filter_names_its_reason(self):
        self.assertEqual(corpus.rejection(stats(fork=True)), "fork")
        self.assertEqual(corpus.rejection(stats(python_share=0.4)), "python share 0.40")
        self.assertEqual(corpus.rejection(stats(authors=3)), "3 authors")
        self.assertEqual(corpus.rejection(stats(days_since_commit=400)), "inactive 400 days")
        self.assertEqual(corpus.rejection(stats(sloc=900)), "production SLOC 900")

    def test_scbench_upstreams_and_stub_packages_are_excluded(self):
        upstream = frozenset({"pyyaml"})
        for name in ("sqlglot", "DuckDB", "PyYAML", "types-requests"):
            self.assertTrue(corpus.excluded_name(name, upstream), name)
        self.assertFalse(corpus.excluded_name("requests", upstream))

    def test_the_source_link_wins_over_the_homepage(self):
        info = {"home_page": "https://github.com/org/site",
                "project_urls": {"Documentation": "https://example.org", "Source": "https://github.com/Org/Lib.git"}}
        self.assertEqual(corpus.github_repo(info), "org/lib")
        self.assertIsNone(corpus.github_repo({"project_urls": {"Home": "https://gitlab.com/a/b"}}))

    def test_release_tags_match_common_spellings(self):
        self.assertEqual(corpus.match_tag(["v1.2.0", "1.1.0"], "lib", "1.2.0"), "v1.2.0")
        self.assertEqual(corpus.match_tag(["my_lib-1.2.0"], "My-Lib", "1.2.0"), "my_lib-1.2.0")
        self.assertIsNone(corpus.match_tag(["v1.2.01"], "lib", "1.2.0"))

    def test_python_share_counts_code_files_only(self):
        sizes = {"a.py": 300, "b.c": 100, "README.md": 10_000}
        self.assertEqual(corpus.python_share(sizes), 0.75)

    def test_upstream_names_drop_stdlib_and_local_modules_and_map_import_names(self):
        names = corpus.upstream_names({"json", "yaml", "helpers", "sqlglot"}, {"helpers"}, frozenset({"json"}))
        self.assertEqual(names, frozenset({"pyyaml", "sqlglot"}))


